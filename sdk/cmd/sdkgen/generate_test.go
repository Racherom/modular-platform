package main

import (
	"bytes"
	"os"
	"strings"
	"testing"
)

const header = `apiVersion: modular-platform/v0alpha1
kind: Module
name: svc
description: A service.
image: example.test/svc:1.0.0
runtime: sdk
`

// TestTestModuleUpToDate keeps the checked in getters of the sdk's test module equal to what
// sdkgen writes from its entry.
func TestTestModuleUpToDate(t *testing.T) {
	t.Parallel()
	entry, err := os.ReadFile("../../internal/testmodule/testmodule.yaml")
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile("../../internal/testmodule/config.gen.go")
	if err != nil {
		t.Fatal(err)
	}
	got, problems := Generate("testmodule.yaml", "testmodule", entry)
	if len(problems) > 0 {
		t.Fatal(problems)
	}
	if !bytes.Equal(got, want) {
		t.Error("internal/testmodule/config.gen.go is stale; run go generate ./...")
	}
}

func TestGenerate(t *testing.T) {
	t.Parallel()
	src, problems := Generate("catalog/svc.yaml", "config", []byte(header+`config:
  wait:
    env: SVC_WAIT
    type: duration
    default: 5s
    description: How long to wait.
`))
	if len(problems) > 0 {
		t.Fatal(problems)
	}
	for _, want := range []string{
		"// Code generated by sdkgen from catalog/svc.yaml. DO NOT EDIT.\n\npackage config\n",
		"import (\n\t\"context\"\n\t\"time\"\n\n\t\"github.com/racherom/modular-platform/sdk\"\n)\n",
		"// Wait is how long to wait.\nfunc (c Config) Wait(ctx context.Context) (time.Duration, error) {",
		`{Name: "wait", Env: "SVC_WAIT", Type: "duration", Default: "5s", Description: "How long to wait."}`,
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("the source lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(string(src), "net/url") {
		t.Error("an import the entry does not need")
	}
}

// TestGenerateUses covers the Uses getters: one per binding with a client, none for an env only
// binding, and the client package imported only then.
func TestGenerateUses(t *testing.T) {
	t.Parallel()
	src, problems := Generate("catalog/svc.yaml", "config", []byte(header+`uses:
  object-store:
    client: http
    env:
      url: STORE_URL
      token_file: STORE_TOKEN_FILE
  cache:
    env:
      host: CACHE_HOST
`))
	if len(problems) > 0 {
		t.Fatal(problems)
	}
	for _, want := range []string{
		"\t\"github.com/racherom/modular-platform/sdk/httpclient\"\n",
		"type Uses struct{ b *sdk.Bindings }\n",
		"// ObjectStore is the client of the object-store binding.\nfunc (u Uses) ObjectStore(ctx context.Context) (*httpclient.Client, error) {\n\treturn sdk.Client[*httpclient.Client](ctx, u.b, \"object-store\")\n}",
		"New: func(_ *sdk.Values, b *sdk.Bindings) (Config, Uses) { return Config{}, Uses{b} },",
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("the source lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(string(src), "Cache(") {
		t.Error("a getter for an env only binding")
	}
}

// TestGenerateRefuses covers sdkgen refusing an entry with the lines the catalog check prints.
func TestGenerateRefuses(t *testing.T) {
	t.Parallel()
	for name, tc := range map[string]struct {
		body string
		want []string
	}{
		"not yaml": {
			body: "config: [",
			want: []string{"catalog/svc.yaml: .: invalid_entry: "},
		},
		"a catalog rule": {
			body: "config:\n  x:\n    env: SVC_X\n    type: float\n    description: X.\n",
			want: []string{"catalog/svc.yaml: config.x.type: invalid_type: "},
		},
		"two getters with one name": {
			body: "config:\n  a-b:\n    env: SVC_A\n    type: string\n    description: A.\n  a--b:\n    env: SVC_B\n    type: string\n    description: B.\n",
			want: []string{"catalog/svc.yaml: config.a-b: name_clash: "},
		},
		"two enum values with one name": {
			body: "config:\n  mode:\n    env: SVC_MODE\n    type: enum\n    values: [a-b, a_b]\n    description: M.\n",
			want: []string{"catalog/svc.yaml: config.mode.values.1: name_clash: "},
		},
		"an enum value without a Go name": {
			body: "config:\n  mode:\n    env: SVC_MODE\n    type: enum\n    values: [\"--\"]\n    description: M.\n",
			want: []string{"catalog/svc.yaml: config.mode.values.0: name_clash: "},
		},
		"a client not available yet": {
			body: "uses:\n  db:\n    client: postgresql\n    env:\n      url: DB_URL\n      database: DB_NAME\n      user: DB_USER\n      password_file: DB_PASSWORD_FILE\n",
			want: []string{"catalog/svc.yaml: uses.db.client: client_not_allowed: "},
		},
		"an enum type that takes a generated name": {
			body: "config:\n  module:\n    env: SVC_MODULE\n    type: enum\n    values: [a]\n    description: M.\n",
			want: []string{"catalog/svc.yaml: config.module: name_clash: "},
		},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			src, problems := Generate("../../catalog/svc.yaml", "config", []byte(header+tc.body))
			if src != nil {
				t.Error("source written for a refused entry")
			}
			if len(problems) != len(tc.want) {
				t.Fatalf("problems = %q, want %d", problems, len(tc.want))
			}
			for i := range tc.want {
				if !strings.HasPrefix(problems[i], tc.want[i]) {
					t.Errorf("problem %d = %q, want prefix %q", i, problems[i], tc.want[i])
				}
			}
		})
	}
}

func TestSourceName(t *testing.T) {
	t.Parallel()
	for in, want := range map[string]string{
		"../../../../catalog/planner.yaml": "catalog/planner.yaml",
		"testmodule.yaml":                  "testmodule.yaml",
		"./a/../catalog/x.yaml":            "catalog/x.yaml",
	} {
		if got := SourceName(in); got != want {
			t.Errorf("SourceName(%q) = %q, want %q", in, got, want)
		}
	}
}
