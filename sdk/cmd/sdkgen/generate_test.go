const header = `apiVersion: modular-platform/v1
kind: Module
name: svc
description: A service.
image: example.test/svc:1.0.0
runtime: sdk
`

// testCaps reads the sdk test module's capabilities: greet and echo (url, token, ca),
// postgresql and s3.
func testCaps(t *testing.T) map[string]manifest.Capability {
	t.Helper()
	caps, err := readCapabilities("../../internal/testmodule/capabilities")
	if err != nil || len(caps) != 4 {
		t.Fatalf("capabilities: %v %v", caps, err)
	}
	return caps
}

// TestTestModuleUpToDate keeps the checked in getters of the sdk's test modules equal to what
// sdkgen writes from their entries.
func TestTestModuleUpToDate(t *testing.T) {
	t.Parallel()
	for _, pkg := range []string{"testmodule", "tlsmodule"} {
		entry, err := os.ReadFile("../../internal/" + pkg + "/" + pkg + ".yaml")
		if err != nil {
			t.Fatal(err)
		}
		want, err := os.ReadFile("../../internal/" + pkg + "/config.gen.go")
		if err != nil {
			t.Fatal(err)
		}
		got, problems := Generate(pkg+".yaml", pkg, entry, testCaps(t))
		if len(problems) > 0 {
			t.Fatal(problems)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("internal/%s/config.gen.go is stale; run go generate ./...", pkg)
		}
	}
}

// TestGenerateNothing covers an entry that declares no value and no client binding: it has no
// getter, so the source imports no context and compiles.
func TestGenerateNothing(t *testing.T) {
	t.Parallel()
	src, problems := Generate("catalog/svc.yaml", "config", []byte(header), testCaps(t))
	if len(problems) > 0 {
		t.Fatal(problems)
	}
	if want := "import (\n\t\"github.com/racherom/modular-platform/sdk\"\n)\n"; !strings.Contains(string(src), want) {
		t.Errorf("the source lacks %q:\n%s", want, src)
	}
}

func TestGenerate(t *testing.T) {
	t.Parallel()
	src, problems := Generate("catalog/svc.yaml", "config", []byte(header+`config:
  wait:
    env: SVC_WAIT
    type: duration
    default: 5s
    description: How long to wait.
`), testCaps(t))
	if len(problems) > 0 {
		t.Fatal(problems)
	}
	for _, want := range []string{
		"// Code generated by sdkgen from catalog/svc.yaml. DO NOT EDIT.\n\npackage config\n",
		"import (\n\t\"context\"\n\t\"time\"\n\n\t\"github.com/racherom/modular-platform/sdk\"\n)\n",
		"// Wait is how long to wait.\nfunc (c Config) Wait(ctx context.Context) (time.Duration, error) {",
		`{Name: "wait", Env: "SVC_WAIT", Type: "duration", Default: "5s", Description: "How long to wait."}`,
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("the source lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(string(src), "net/url") {
		t.Error("an import the entry does not need")
	}
}

// TestGenerateUses covers the Uses getters: one per binding with a client, none for an env only
// binding, and the client package imported only then.
func TestGenerateUses(t *testing.T) {
	t.Parallel()
	src, problems := Generate("catalog/svc.yaml", "config", []byte(header+`uses:
  object-store:
    capability: echo
    client: http
    env:
      url: STORE_URL
      token: STORE_TOKEN_FILE
  cache:
    capability: postgresql
    env:
      host: CACHE_HOST
`), testCaps(t))
	if len(problems) > 0 {
		t.Fatal(problems)
	}
	for _, want := range []string{
		"\t\"github.com/racherom/modular-platform/sdk/httpclient\"\n",
		"type Uses struct{ b *sdk.Bindings }\n",
		"// ObjectStore is the client of the object-store binding.\nfunc (u Uses) ObjectStore(ctx context.Context) (*httpclient.Client, error) {\n\treturn sdk.Client[*httpclient.Client](ctx, u.b, \"object-store\")\n}",
		"New: func(_ *sdk.Values, b *sdk.Bindings) (Config, Uses) { return Config{}, Uses{b} },",
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("the source lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(string(src), "Cache(") {
		t.Error("a getter for an env only binding")
	}
}

