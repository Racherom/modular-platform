// goTypes maps a value type to the Go type its getter returns; enum gets its own named type.
var goTypes = map[string]string{
	manifest.TypeString:   "string",
	manifest.TypeInt:      "int",
	manifest.TypeBool:     "bool",
	manifest.TypeDuration: "time.Duration",
	manifest.TypeURL:      "*url.URL",
	manifest.TypeSecret:   "sdk.Secret",
}

// Generate returns the gofmt formatted Go source for the entry, or the problems that refuse it,
// as catalog/<file>: <dotted.path>: <code>: <message> lines.
func Generate(source, pkg string, data []byte) ([]byte, []string) {
	file := path.Base(source)
	e, err := manifest.Parse(data)
	if err != nil {
		return nil, []string{fmt.Sprintf("catalog/%s: .: invalid_entry: the entry could not be read: %s", file, oneLine(err))}
	}
	var problems []string
	for _, p := range manifest.Check(e) {
		problems = append(problems, fmt.Sprintf("catalog/%s: %s: %s: %s", file, p.Path, p.Code, p.Message))
	}
	if len(problems) > 0 {
		return nil, problems
	}
	g := generator{file: file, entry: e, idents: map[string]string{"Config": "the Config type", "Uses": "the Uses type", "Module": "the Module value"}}
	src := g.source(source, pkg)
	if len(g.problems) > 0 {
		return nil, g.problems
	}
	formatted, err := format.Source(src)
	if err != nil {
		return nil, []string{fmt.Sprintf("sdkgen: the generated code does not parse: %v", err)}
	}
	return formatted, nil
}

type generator struct {
	file     string
	entry    manifest.Entry
	idents   map[string]string // package level Go names to what took them, to catch clashes
	problems []string
	imports  map[string]bool
}

func (g *generator) claim(ident, what, path string) {
	if first, ok := g.idents[ident]; ok {
		g.problems = append(g.problems, fmt.Sprintf("catalog/%s: %s: name_clash: %s becomes %s, like %s", g.file, path, what, ident, first))
		return
	}
	g.idents[ident] = what
}

func (g *generator) source(source, pkg string) []byte {
	g.imports = map[string]bool{"github.com/racherom/modular-platform/sdk": true}
	names := sortedKeys(g.entry.Config)
	caps := sortedKeys(g.entry.Uses)

	var body bytes.Buffer
	getters := map[string]string{}
	for _, name := range names {
		v := g.entry.Config[name]
		goName := manifest.GoName(name)
		if first, ok := getters[goName]; ok {
			g.problems = append(g.problems, fmt.Sprintf("catalog/%s: config.%s: name_clash: the getter %s is also the getter of %s", g.file, name, goName, first))
		}
		getters[goName] = name
		if v.Type == manifest.TypeEnum {
			g.enum(&body, name, goName, v)
		}
	}

	fmt.Fprintf(&body, "// Config holds the %s module's declared values; read them only through the getters.\n", g.entry.Name)
	if len(names) == 0 {
		body.WriteString("type Config struct{}\n\n")
	} else {
		body.WriteString("type Config struct{ v *sdk.Values }\n\n")
	}
	for _, name := range names {
		g.getter(&body, name, manifest.GoName(name), g.entry.Config[name])
	}

	var clients []string
	for _, c := range caps {
		if g.entry.Uses[c].Client != "" {
			clients = append(clients, c)
		}
	}
	fmt.Fprintf(&body, "// Uses holds the %s module's binding clients", g.entry.Name)
	if len(clients) == 0 {
		body.WriteString(" (none).\ntype Uses struct{}\n\n")
	} else {
		body.WriteString("; read them only through the getters.\ntype Uses struct{ b *sdk.Bindings }\n\n")
	}
	usesGetters := map[string]string{}
	for _, c := range clients {
		goName := manifest.GoName(c)
		if first, ok := usesGetters[goName]; ok {
			g.problems = append(g.problems, fmt.Sprintf("catalog/%s: uses.%s: name_clash: the getter %s is also the getter of %s", g.file, c, goName, first))
		}
		usesGetters[goName] = c
		g.client(&body, c, goName, g.entry.Uses[c])
	}

	if len(names) > 0 || len(clients) > 0 {
		g.imports["context"] = true // every getter takes ctx
	}
	g.declaration(&body, names, caps, len(clients) > 0)

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by sdkgen from %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", source, pkg)
	imports := make([]string, 0, len(g.imports))
	for imp := range g.imports {
		imports = append(imports, imp)
	}
	// standard library first, then a blank line, then the sdk and its clients
	std := func(imp string) bool { return !strings.Contains(strings.SplitN(imp, "/", 2)[0], ".") }
	slices.SortFunc(imports, func(a, b string) int {
		if std(a) != std(b) {
			if std(a) {
				return -1
			}
			return 1
		}
		return strings.Compare(a, b)
	})
	for i, imp := range imports {
		if i > 0 && std(imports[i-1]) && !std(imp) {
			out.WriteString("\n")
		}
		fmt.Fprintf(&out, "\t%q\n", imp)
	}
	out.WriteString(")\n\n")
	out.Write(body.Bytes())
	return out.Bytes()
}

func (g *generator) enum(b *bytes.Buffer, name, typeName string, v manifest.Value) {
	g.claim(typeName, "the enum type of "+name, "config."+name)
	fmt.Fprintf(b, "// %s is a value of %s.\ntype %s string\n\n", typeName, name, typeName)
	fmt.Fprintf(b, "// The values %s takes.\nconst (\n", typeName)
	for i, value := range v.Values {
		suffix := manifest.GoName(value)
		if suffix == "" {
			g.problems = append(g.problems, fmt.Sprintf("catalog/%s: config.%s.values.%d: name_clash: %q gives no Go name", g.file, name, i, value))
			continue
		}
		g.claim(typeName+suffix, fmt.Sprintf("the enum value %q of %s", value, name), fmt.Sprintf("config.%s.values.%d", name, i))
		fmt.Fprintf(b, "\t%s%s %s = %s\n", typeName, suffix, typeName, strconv.Quote(value))
	}
	b.WriteString(")\n\n")
}

func (g *generator) getter(b *bytes.Buffer, name, goName string, v manifest.Value) {
	goType := goTypes[v.Type]
	switch v.Type {
	case manifest.TypeEnum:
		goType = goName
	case manifest.TypeDuration:
		g.imports["time"] = true
	case manifest.TypeURL:
		g.imports["net/url"] = true
	}
	fmt.Fprintf(b, "// %s is %s\n", goName, docSentence(v.Description))
	lookup := v.Optional && v.Default == nil
	if lookup {
		fmt.Fprintf(b, "// The bool reports whether it is set.\n")
		fmt.Fprintf(b, "func (c Config) %s(ctx context.Context) (%s, bool, error) {\n", goName, goType)
	} else {
		fmt.Fprintf(b, "func (c Config) %s(ctx context.Context) (%s, error) {\n", goName, goType)
	}
	q := strconv.Quote(name)
	switch {
	case v.Type == manifest.TypeEnum && lookup:
		fmt.Fprintf(b, "\ts, ok, err := sdk.Lookup[string](ctx, c.v, %s)\n\treturn %s(s), ok, err\n", q, goType)
	case v.Type == manifest.TypeEnum:
		fmt.Fprintf(b, "\ts, err := sdk.Value[string](ctx, c.v, %s)\n\treturn %s(s), err\n", q, goType)
	case v.Type == manifest.TypeURL && lookup:
		fmt.Fprintf(b, "\tu, ok, err := sdk.Lookup[url.URL](ctx, c.v, %s)\n\tif err != nil || !ok {\n\t\treturn nil, ok, err\n\t}\n\treturn &u, true, nil\n", q)
	case v.Type == manifest.TypeURL:
		fmt.Fprintf(b, "\tu, err := sdk.Value[url.URL](ctx, c.v, %s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn &u, nil\n", q)
	case lookup:
		fmt.Fprintf(b, "\treturn sdk.Lookup[%s](ctx, c.v, %s)\n", goType, q)
	default:
		fmt.Fprintf(b, "\treturn sdk.Value[%s](ctx, c.v, %s)\n", goType, q)
	}
	b.WriteString("}\n\n")
}

// clientType is what sdkgen writes for one client kind: the Go type its getter returns, the
// package of that type, and the sdk.Opener that opens it (in package openPkg).
type clientType struct{ goType, pkg, open, openPkg string }

// clientTypes maps a client kind to its clientType; the kinds missing here are not available in
// this sdk version yet.
var clientTypes = map[string]clientType{
	manifest.ClientHTTP:       {"*httpclient.Client", sdkPkg + "/httpclient", "httpclient.Open", sdkPkg + "/httpclient"},
	manifest.ClientPostgreSQL: {"*pgxpool.Pool", "github.com/jackc/pgx/v5/pgxpool", "pg.Open", sdkPkg + "/pg"},
	manifest.ClientS3:         {"*s3.Client", sdkPkg + "/s3", "s3.Open", sdkPkg + "/s3"},
}

const sdkPkg = "github.com/racherom/modular-platform/sdk"

func (g *generator) client(b *bytes.Buffer, capability, goName string, u manifest.Use) {
	ct, ok := clientTypes[u.Client]
	if !ok {
		g.problems = append(g.problems, fmt.Sprintf("catalog/%s: uses.%s.client: client_not_allowed: the %s client is not available in this sdk version yet", g.file, capability, u.Client))
		return
	}
	g.imports[ct.pkg], g.imports[ct.openPkg] = true, true
	fmt.Fprintf(b, "// %s is the client of the %s binding.\n", goName, capability)
	if u.Optional {
		fmt.Fprintf(b, "// It returns sdk.ErrUnbound when the graph leaves %s unbound.\n", capability)
	}
	fmt.Fprintf(b, "func (u Uses) %s(ctx context.Context) (%s, error) {\n", goName, ct.goType)
	fmt.Fprintf(b, "\treturn sdk.Client[%s](ctx, u.b, %s)\n}\n\n", ct.goType, strconv.Quote(capability))
}

func (g *generator) declaration(b *bytes.Buffer, names, caps []string, clients bool) {
	b.WriteString("// Module is the declaration sdk.Run loads.\n")
	b.WriteString("var Module = sdk.Declaration[Config, Uses]{\n")
	fmt.Fprintf(b, "\tName: %s,\n", strconv.Quote(g.entry.Name))
	if len(names) > 0 {
		b.WriteString("\tValues: []sdk.ValueSpec{\n")
		for _, name := range names {
			b.WriteString("\t\t{" + valueSpec(name, g.entry.Config[name]) + "},\n")
		}
		b.WriteString("\t},\n")
	}
	if len(caps) > 0 {
		b.WriteString("\tBindings: []sdk.BindingSpec{\n")
		for _, c := range caps {
			u := g.entry.Uses[c]
			fields := []string{"Capability: " + strconv.Quote(c)}
			if u.Client != "" {
				fields = append(fields, "Client: "+strconv.Quote(u.Client))
			}
			if u.Optional {
				fields = append(fields, "Optional: true")
			}
			if len(u.Env) > 0 {
				var env []string
				for _, k := range sortedKeys(u.Env) {
					env = append(env, strconv.Quote(k)+": "+strconv.Quote(u.Env[k]))
				}
				fields = append(fields, "Env: map[string]string{"+strings.Join(env, ", ")+"}")
			}
			if ct, ok := clientTypes[u.Client]; ok {
				fields = append(fields, "Open: "+ct.open)
			}
			b.WriteString("\t\t{" + strings.Join(fields, ", ") + "},\n")
		}
		b.WriteString("\t},\n")
	}
	for _, c := range sortedKeys(g.entry.Provides) {
		p := g.entry.Provides[c]
		fields := []string{"Capability: " + strconv.Quote(c)}
		if p.Auth != "" {
			fields = append(fields, "Auth: "+strconv.Quote(p.Auth))
		}
		if p.Env != nil && p.Env.ClientsDir != "" {
			fields = append(fields, "ClientsDirEnv: "+strconv.Quote(p.Env.ClientsDir))
		}
		fmt.Fprintf(b, "\tProvides: &sdk.ProvideSpec{%s},\n", strings.Join(fields, ", "))
	}
	v, cfg, bnd, uses := "_", "Config{}", "_", "Uses{}"
	if len(names) > 0 {
		v, cfg = "v", "Config{v}"
	}
	if clients {
		bnd, uses = "b", "Uses{b}"
	}
	if v == "_" && bnd == "_" {
		b.WriteString("\tNew: func(*sdk.Values, *sdk.Bindings) (Config, Uses) { return Config{}, Uses{} },\n")
	} else {
		fmt.Fprintf(b, "\tNew: func(%s *sdk.Values, %s *sdk.Bindings) (Config, Uses) { return %s, %s },\n", v, bnd, cfg, uses)
	}
	b.WriteString("}\n")
}

func valueSpec(name string, v manifest.Value) string {
	fields := []string{
		"Name: " + strconv.Quote(name),
		"Env: " + strconv.Quote(v.Env),
		"Type: " + strconv.Quote(v.Type),
	}
	if v.Default != nil {
		fields = append(fields, "Default: "+strconv.Quote(*v.Default))
	}
	if v.Optional {
		fields = append(fields, "Optional: true")
	}
	if v.Min != nil {
		fields = append(fields, "Min: "+strconv.Quote(v.Min.Text))
	}
	if v.Max != nil {
		fields = append(fields, "Max: "+strconv.Quote(v.Max.Text))
	}
	if v.Pattern != nil {
		fields = append(fields, "Pattern: "+strconv.Quote(*v.Pattern))
	}
	if len(v.Values) > 0 {
		var quoted []string
		for _, s := range v.Values {
			quoted = append(quoted, strconv.Quote(s))
		}
		fields = append(fields, "Values: []string{"+strings.Join(quoted, ", ")+"}")
	}
	if v.Generate {
		fields = append(fields, "Generate: true")
	}
	fields = append(fields, "Description: "+strconv.Quote(v.Description))
	return strings.Join(fields, ", ")
}

// docSentence turns a description into the rest of "<Getter> is ...": the first letter lower
// case unless it starts an acronym, and a closing period.
func docSentence(d string) string {
	d = strings.TrimSpace(d)
	r := []rune(d)
	if len(r) > 1 && unicode.IsUpper(r[0]) && !unicode.IsUpper(r[1]) {
		r[0] = unicode.ToLower(r[0])
	}
	d = string(r)
	if !strings.HasSuffix(d, ".") {
		d += "."
	}
	return d
}

func oneLine(err error) string {
	return strings.Join(strings.Fields(err.Error()), " ")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
